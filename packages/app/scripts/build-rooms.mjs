// Bundles the den builder into IWER GLTS room files (public/rooms/yadori_den.glts and
// yadori_bare.glts). Run after changing src/den/den.ts: `pnpm --filter app rooms`.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..');
for (const variant of ['den', 'bare']) {
  await build({
    entryPoints: [resolve(app, 'src/den/glts-entry.ts')],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    external: ['three', '@drawcall/glts'],
    define: { __DEN_VARIANT__: JSON.stringify(variant) },
    outfile: resolve(app, `public/rooms/yadori_${variant}.glts`),
    banner: { js: `// yadori_${variant}: generated by scripts/build-rooms.mjs from src/den/den.ts. MIT, (c) 2026 Nivesh Gajengi.` },
    logLevel: 'warning',
  });
  console.log(`public/rooms/yadori_${variant}.glts`);
}
